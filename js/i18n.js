let lang = 'zh';
try { lang = localStorage.getItem('ppm-lang') || (navigator.language.startsWith('zh') ? 'zh' : 'en'); } catch { /* ignore */ }

export function getLang() { return lang; }
export function setLang(l) {
  lang = l;
  try { localStorage.setItem('ppm-lang', l); } catch { /* ignore */ }
}
export function t(key, vars) {
  let s = (STRINGS[lang] && STRINGS[lang][key]) ?? STRINGS.zh[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, v);
  return s;
}
export function applyI18n(root = document) {
  document.documentElement.lang = lang === 'zh' ? 'zh-CN' : 'en';
  root.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-ph]').forEach(el => { el.placeholder = t(el.dataset.i18nPh); });
  root.querySelectorAll('[data-i18n-title]').forEach(el => { el.title = t(el.dataset.i18nTitle); });
  document.title = t('appTitle') + ' · Perler Pattern Maker';
}
